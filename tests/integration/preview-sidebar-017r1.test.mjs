  await act(async () => root.render(createElement(TooltipProvider, null, createElement(PreviewSidebar, {view: 'object', model: {project: facts.foundation, pages: facts.pages.items, relations: facts.relations.items}, pageId: 'page_events_home', inspectedObject: object, onNavigate: (value) => navigation.push(value), onPreview: (value) => previews.push(value), onCopyTask: (value) => { copied = value; }}))));
  assert.match(container.textContent, /已锁定对象/);
