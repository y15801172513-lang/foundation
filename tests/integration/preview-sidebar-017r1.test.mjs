  assert.match(leafRow.querySelector('[data-inspector-tree-spacer]').className, /shrink-0/);
  await act(async () => leaf.dispatchEvent(new MouseEvent('click', {bubbles: true})));
  assert.deepEqual(navigation, [{inspectorId: 'component:component_event_action:event_action_manage'}], '逐级展开后的叶节点必须可点击定位');
  assert.equal(container.querySelector('input'), null);
  const copy = [...container.querySelectorAll('button')].find((button) => button.textContent.includes('复制'));
  await act(async () => copy.dispatchEvent(new MouseEvent('click', {bubbles: true})));
  const menuItems = [...document.querySelectorAll('[data-slot="dropdown-menu-item"]')];
  assert.deepEqual(menuItems.map((item) => item.textContent), ['完整对象上下文', '身份与层级', '相关逻辑', '布局与样式', '使用、影响与缺口']);
  await act(async () => menuItems[1].dispatchEvent(new MouseEvent('click', {bubbles: true})));
  assert.match(copied, /Foundation 检查对象上下文 · 身份与层级/);
  assert.match(copied, /object stable identity/);
